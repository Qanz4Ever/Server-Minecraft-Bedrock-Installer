    local gamemode="$2"
    local difficulty="$3"
    local allow_cheats="$4"
    local server_port="$5"
    local level_name="$6"
    local level_seed="$7"
    local server_dir="$8"
    
    print_doing "Generating server.properties..."
    
    cat > "$server_dir/server.properties" << EOF
