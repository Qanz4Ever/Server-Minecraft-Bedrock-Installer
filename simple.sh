# ANSI color codes
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
CYAN='\033[0;36m'
BLUE='\033[0;34m'
PURPLE='\033[0;35m'
WHITE='\033[1;37m'
NC='\033[0m' # No Color

# Base directories
BASE_DIR="/home/minecraft"
SCRIPT_NAME=$(basename "$0")
VERSION="v1.0 Clean Edition (Fixed)"

# Check if running in container/without systemd
USING_SYSTEMD=false
if pidof systemd >/dev/null 2>&1 && [ "$(ps -p1 -o comm= 2>/dev/null)" = "systemd" ]; then
    USING_SYSTEMD=true
fi

# ============================================
# UTILITY FUNCTIONS
# ============================================

print_header() {
    clear
    echo -e "${CYAN}========================================${NC}"
    echo -e "${WHITE}   Minecraft Bedrock Manager ${VERSION}${NC}"
    echo -e "${CYAN}========================================${NC}"
    echo ""
}

print_success() {
    echo -e "${GREEN}[SUCCESS]${NC} $1"
}

print_error() {
    echo -e "${RED}[ERROR]${NC} $1"
}

print_warning() {
    echo -e "${YELLOW}[WARNING]${NC} $1"
}

print_info() {
    echo -e "${CYAN}[INFO]${NC} $1"
}

print_doing() {
    echo -e "${BLUE}[DOING]${NC} $1"
}

check_root() {
    if [[ $EUID -ne 0 ]]; then
        print_error "This script must be run as root"
        exit 1
    fi
}

# Trap Ctrl+C for clean exit
trap_ctrl_c() {
    echo ""
    print_warning "Interrupted by user"
    sleep 1
    return 2
}

# ============================================
# DEPENDENCY INSTALLATION
# ============================================

install_dependencies() {
    print_doing "Checking and installing dependencies..."
    
    # Update package list
    apt-get update -qq > /dev/null 2>&1
    
    # Install required packages
    DEPS=("unzip" "curl" "wget" "tmux" "openssh-server" "procps" "htop")
    
    for dep in "${DEPS[@]}"; do
        if ! command -v "$dep" &> /dev/null; then
            print_doing "Installing $dep..."
            apt-get install -y "$dep" > /dev/null 2>&1
            print_success "$dep installed"
        else
            print_success "$dep already installed"
        fi
    done
    
    # Ensure tmux is available
    if ! command -v tmux &> /dev/null; then
        print_error "tmux installation failed"
        exit 1
    fi
    
    print_success "All dependencies installed"
}

# ============================================
# SERVER PROPERTIES GENERATOR
# ============================================

generate_server_properties() {
